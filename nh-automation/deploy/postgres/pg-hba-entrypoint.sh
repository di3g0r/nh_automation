#!/bin/sh
# Prod db entrypoint wrapper (phase 4, NFR-1/NFR-2).
#
# Writes pg_hba.conf from the environment, then starts the official postgres
# entrypoint with it:
#   - PLC logins (members of the plc_machine role) only from PLC_ALLOWED_NETWORKS
#     (comma-separated CIDRs), with scram-sha-256; from anywhere else: rejected.
#   - Every other user (the app, the backup job) only from the Docker network
#     DOCKER_SUBNET, with scram-sha-256.
#   - Everything else: rejected.
# The PostgreSQL port is published on the server only for the PLCs; also
# restrict it with the firewall (see README "PLC database access").
set -eu

HBA=/etc/postgresql/pg_hba.conf
mkdir -p /etc/postgresql

{
  echo "# Generated by deploy/postgres/pg-hba-entrypoint.sh at container start. Do not edit."
  echo "# TYPE  DATABASE  USER          ADDRESS  METHOD"
  echo "local   all       all                    trust"
  for cidr in $(echo "${PLC_ALLOWED_NETWORKS:-}" | tr ',' ' '); do
    echo "host    all       +plc_machine  ${cidr}  scram-sha-256"
  done
  echo "host    all       +plc_machine  0.0.0.0/0  reject"
  echo "host    all       +plc_machine  ::/0       reject"
  echo "host    all       all           ${DOCKER_SUBNET:-172.28.0.0/16}  scram-sha-256"
  echo "host    all       all           0.0.0.0/0  reject"
  echo "host    all       all           ::/0       reject"
} > "$HBA"
chmod 644 "$HBA"

exec docker-entrypoint.sh "$@" -c hba_file="$HBA"
